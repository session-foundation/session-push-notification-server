-- The schema as it stood before migrations were recorded, written to run against a database made
-- then as well as an empty one: every statement is a no-op where its change is already there, and
-- the old upgrade steps are folded in, so that any such database is brought level.

CREATE TABLE IF NOT EXISTS subscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account BYTEA NOT NULL,       -- 33-byte swarm account id (e.g. session id or closed group id)
    session_ed25519 BYTEA,        -- for a 05 account (session id) this is the 32-byte ed25519 key
    subaccount_tag BYTEA,         -- optional subaccount tag for subaccount authentication
    subaccount_sig BYTEA,         -- optional subaccount tag signature for subaccount authentication
    signature BYTEA NOT NULL,     -- subscription authentication signature (for swarm)
    signature_ts BIGINT NOT NULL, -- unix timestamp of the auth signature (for swarm)
    want_data BOOLEAN NOT NULL,   -- whether the client wants msg data included in the notification
    enc_key BYTEA NOT NULL,       -- encryption key with which we encrypt the payload
    service VARCHAR NOT NULL,     -- subscription service type ("apns", "firebase")
    svcid VARCHAR NOT NULL,       -- unique device/app identifier
    svcdata BYTEA,                -- arbitrary data for subscription service

    UNIQUE(account, service, svcid)
);

-- A table that already existed skips the CREATE above whole, constraint and all, and Postgres has no
-- ADD CONSTRAINT IF NOT EXISTS: so it is added, under the name the CREATE gives it, only if absent.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT FROM pg_constraint
        WHERE conrelid = 'subscriptions'::regclass
            AND conname = 'subscriptions_account_service_svcid_key'
    ) THEN
        ALTER TABLE subscriptions
            ADD CONSTRAINT subscriptions_account_service_svcid_key UNIQUE (account, service, svcid);
    END IF;
END
$$;

ALTER TABLE subscriptions ADD COLUMN IF NOT EXISTS subaccount_tag BYTEA;
ALTER TABLE subscriptions ADD COLUMN IF NOT EXISTS subaccount_sig BYTEA;
ALTER TABLE subscriptions DROP COLUMN IF EXISTS subkey_tag;

CREATE INDEX IF NOT EXISTS subscriptions_signature_ts_idx ON subscriptions(signature_ts);

CREATE INDEX IF NOT EXISTS subscriptions_service_idx ON subscriptions(service);

CREATE TABLE IF NOT EXISTS sub_namespaces (
    subscription BIGINT NOT NULL REFERENCES subscriptions ON DELETE CASCADE,
    namespace SMALLINT NOT NULL,

    PRIMARY KEY(subscription, namespace)
);

CREATE TABLE IF NOT EXISTS service_stats (
    service VARCHAR NOT NULL,
    name VARCHAR NOT NULL,
    val_str VARCHAR,
    val_int BIGINT,

    PRIMARY KEY(service, name),
    CHECK((val_str IS NULL AND val_int IS NOT NULL) OR (val_str IS NOT NULL AND val_int IS NULL))
);
